// Usage: node tools/shot2.mjs <out-prefix>   Screenshots the dashboard and runs the Collector flow end to end.
import { chromium } from 'playwright-core';
const prefix = process.argv[2];
const exe = process.env.CHROMIUM_PATH || '/opt/pw-browsers/chromium-1194/chrome-linux/chrome';
const browser = await chromium.launch({ executablePath: exe, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1680, height: 1050 } });
const logs = [];
page.on('console', (m) => { const t = m.text(); if (!/License|\*\*\*|React DevTools|vite\]|unlocked for trial|watermark/.test(t)) logs.push(`[${m.type()}] ${t}`); });
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
await page.goto('http://localhost:5173/', { waitUntil: 'networkidle' });
await page.waitForSelector('svg', { timeout: 20000 });
await page.waitForTimeout(2200);
await page.screenshot({ path: `${prefix}-dash.png` });
await page.getByRole('button', { name: 'Collector agent' }).click();
await page.waitForTimeout(3000);
await page.screenshot({ path: `${prefix}-collector0.png` });
await page.getByText('Propose the best reminders').click();
await page.waitForTimeout(6000);
await page.screenshot({ path: `${prefix}-collector1.png` });
console.log(logs.slice(0, 30).join('\n'));
await browser.close();
